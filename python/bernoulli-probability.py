# Задача: реализовать формулу Бернулли — вероятность того, что при N 
# независимых испытаниях (с вероятностью успеха p в каждом) произойдёт 
# ровно k успехов.
# Применение: вероятность ровно k случаев мошенничества среди N транзакций 
# при известной базовой частоте фрода p.

def factorial(n: int) -> int:
    result = 1
    for i in range(1, n + 1):
        result *= i
    return result

def bernoulli_probability(n, k, p):
    return factorial(n) / (factorial(k) * factorial(n - k)) * p**k * (1 - p)**(n - k)

# Пример: вероятность ровно 3 мошеннических транзакций из 10,
# если базовая частота фрода p = 0.05
print(bernoulli_probability(n=10, k=3, p=0.05))
